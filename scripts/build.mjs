// A deterministic, dependency-free build for this deliberately small client.
// Host sources stay ESM; only the browser entry is wrapped in DSH's shared
// module loader. Never copies, rewrites, or patches any DSH core source.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { Script } from 'node:vm';

const root = fileURLToPath(new URL('../', import.meta.url));
// Importing this renderer only reads source; it never creates build outputs.
export async function renderClient() {
  const modules = ['native.js', 'styles.js', 'index.js'];
  const parts = [];
  for (const file of modules) {
    const path = resolve(root, 'src/client', file);
    let source = (await readFile(path, 'utf8')).replace(/\r\n/g, '\n');
    // Accept only the entry's known, static imports. This is not a general
    // JavaScript bundler; fail closed rather than ship unresolved ESM.
    source = source.replace(/^import React from ['"]react['"];?\s*$/gm, '');
    source = source.replace(/^import \{ MenuItemButton \} from ['"]@deepseek-ai\/dsh-client-ui-primitives['"];?\s*$/gm, '');
    source = source.replace(/^import\s*\{[A-Za-z_$\s,]+\}\s*from ['"]\.\/(?:native|styles)\.js['"];?\s*$/gm, '');
    source = source.replace(/^export\s+(?=(?:async\s+)?function\s|class\s|const\s|let\s|var\s)/gm, '');
    if (/^\s*(?:import|export)\s/m.test(source) || /\bimport\s*\(/m.test(source)) {
      throw new Error(`Unsupported module syntax in ${file}; extend the explicit build, do not silently drop it.`);
    }
    parts.push(`// Source: src/client/${file}\n${source.trim()}\n`);
  }
  const output = `// Generated by scripts/build.mjs. Do not edit.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-plugin-side-chat-native',\n  factory(require) {\n    'use strict';\n    const React = require('react');\n    const { MenuItemButton } = require('@deepseek-ai/dsh-client-ui-primitives');\n${parts.join('\n')}\n    return { apply, inject };\n  }\n});\n`;
  new Script(output, { filename: 'dsh-plugin-side-chat-native/lib/client.js' });
  return output;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length > 3 || (process.argv[2] && process.argv[2] !== '--check')) throw new Error('Only --check is supported');
  const output = await renderClient(), destination = resolve(root, 'lib/client.js');
  if (process.argv[2] === '--check') {
    if (await readFile(destination, 'utf8') !== output) throw new Error('Client bundle is stale; run node scripts/build.mjs before testing or packaging.');
    console.log('Verified client bundle matches current source (read-only).');
  } else {
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, output, 'utf8');
    console.log(`Built dsh-plugin-side-chat-native client (${Buffer.byteLength(output)} bytes); host ESM unchanged.`);
  }
}
